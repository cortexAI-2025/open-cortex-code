digest="${repo_digest##*@}"
case "$image_id" in sha256:????????????????????????????????????????????????????????????????) ;; *) echo 'NOT RUN image-id-invalid'; exit 77;; esac
case "$digest" in sha256:????????????????????????????????????????????????????????????????) ;; *) echo 'NOT RUN immutable-repo-digest-unavailable'; exit 77;; esac
printf '%s\n' "$image_id" > "$out/06-image-id.txt"
printf '%s\n' "$repo_digest" > "$out/06-repo-digest.txt"
printf 'localhost/open-cortex-runner@%s\n' "$digest" | tee "$out/06-image-reference.txt"
